<?php
require_once __DIR__ . "/db.php";
require_once __DIR__ . "/auth.php";
require_once __DIR__ . "/layout.php";

require_access("instructors");

$canEdit = can_edit();

$message = "";
$error = "";

$uploadDir = __DIR__ . "/uploads/instructors/";
$uploadUrl = "uploads/instructors/";

$salutations = ["Mr.", "Ms.", "Mrs.", "Dr.", "Engr.", "Prof."];

// Create the upload directory if it does not exist.
if (!is_dir($uploadDir)) {
    if (!mkdir($uploadDir, 0755, true) && !is_dir($uploadDir)) {
        error_log("Unable to create instructor upload directory.");
    }
}

// Save a photo and return [filename, error message].
function save_instructor_photo(array $file, string $uploadDir): array
{
    if (($file["error"] ?? UPLOAD_ERR_NO_FILE) === UPLOAD_ERR_NO_FILE) {
        return [null, ""];
    }

    if (($file["error"] ?? UPLOAD_ERR_NO_FILE) !== UPLOAD_ERR_OK) {
        return [null, "Photo upload failed. Please try again."];
    }

    if (!isset($file["tmp_name"], $file["size"])) {
        return [null, "Invalid photo upload."];
    }

    if ($file["size"] <= 0 || $file["size"] > 2 * 1024 * 1024) {
        return [null, "Photo must be greater than 0 bytes and no larger than 2MB."];
    }

    if (!is_uploaded_file($file["tmp_name"])) {
        return [null, "Invalid uploaded file."];
    }

    $finfo = new finfo(FILEINFO_MIME_TYPE);
    $mime = $finfo->file($file["tmp_name"]);

    $allowed = [
        "image/jpeg" => "jpg",
        "image/png"  => "png",
        "image/gif"  => "gif",
        "image/webp" => "webp",
    ];

    if (!isset($allowed[$mime]) || @getimagesize($file["tmp_name"]) === false) {
        return [null, "Please upload a valid JPG, PNG, GIF, or WEBP image."];
    }

    if (
        !is_dir($uploadDir) &&
        !mkdir($uploadDir, 0755, true) &&
        !is_dir($uploadDir)
    ) {
        return [null, "The photo upload folder could not be created."];
    }

    $filename = bin2hex(random_bytes(12)) . "." . $allowed[$mime];
    $destination = $uploadDir . $filename;

    if (!move_uploaded_file($file["tmp_name"], $destination)) {
        return [null, "Could not save the uploaded photo. Check folder permissions."];
    }

    return [$filename, ""];
}

// Delete only filenames generated by this application.
function delete_instructor_photo(?string $filename, string $uploadDir): void
{
    if (
        $filename !== null &&
        preg_match('/^[a-f0-9]{24}\.(jpg|png|gif|webp)$/', $filename) &&
        is_file($uploadDir . $filename)
    ) {
        @unlink($uploadDir . $filename);
    }
}

// ADD, UPDATE, AND DELETE
if ($_SERVER["REQUEST_METHOD"] === "POST") {
    if (!$canEdit) {
        http_response_code(403);
        exit("You do not have permission to modify instructors.");
    }

    csrf_check();

    $action = (string)($_POST["action"] ?? "");
    $id = filter_var($_POST["id"] ?? 0, FILTER_VALIDATE_INT);
    $uploadedPhoto = null;

    try {
        if ($action === "delete") {
            if (!$id || $id < 1) {
                throw new InvalidArgumentException("Invalid instructor ID.");
            }

            $stmt = $conn->prepare(
                "SELECT PHOTO FROM tbl_instructors WHERE ID = ?"
            );
            $stmt->bind_param("i", $id);
            $stmt->execute();
            $old = $stmt->get_result()->fetch_assoc();
            $stmt->close();

            if (!$old) {
                throw new InvalidArgumentException("Instructor not found.");
            }

            $stmt = $conn->prepare(
                "DELETE FROM tbl_instructors WHERE ID = ?"
            );
            $stmt->bind_param("i", $id);
            $stmt->execute();
            $stmt->close();

            delete_instructor_photo($old["PHOTO"] ?? null, $uploadDir);
            header("Location: instructors.php?deleted=1");
            exit();
        }

        if ($action !== "add" && $action !== "update") {
            throw new InvalidArgumentException("Invalid action.");
        }

        $salutation = trim((string)($_POST["salutation"] ?? ""));
        $firstname = trim((string)($_POST["firstname"] ?? ""));
        $middlename = trim((string)($_POST["middlename"] ?? ""));
        $lastname = trim((string)($_POST["lastname"] ?? ""));

        if (!in_array($salutation, $salutations, true)) {
            throw new InvalidArgumentException("Please select a valid salutation.");
        }

        if ($firstname === "" || $lastname === "") {
            throw new InvalidArgumentException(
                "First name and last name are required."
            );
        }

        if (
            mb_strlen($firstname) > 100 ||
            mb_strlen($middlename) > 100 ||
            mb_strlen($lastname) > 100
        ) {
            throw new InvalidArgumentException(
                "Names must not exceed 100 characters."
            );
        }

        if ($action === "update" && (!$id || $id < 1)) {
            throw new InvalidArgumentException("Invalid instructor ID.");
        }

        // Upload a new photo if one was selected.
        [$uploadedPhoto, $photoError] = save_instructor_photo(
            $_FILES["photo"] ?? ["error" => UPLOAD_ERR_NO_FILE],
            $uploadDir
        );

        if ($photoError !== "") {
            throw new InvalidArgumentException($photoError);
        }

        if ($action === "add") {
            $photo = $uploadedPhoto;

            $stmt = $conn->prepare(
                "INSERT INTO tbl_instructors
                    (SALUTATION, FIRSTNAME, MIDDLENAME, LASTNAME, PHOTO)
                 VALUES (?, ?, ?, ?, ?)"
            );

            $stmt->bind_param(
                "sssss",
                $salutation,
                $firstname,
                $middlename,
                $lastname,
                $photo
            );

            $stmt->execute();
            $stmt->close();

            header("Location: instructors.php?added=1");
            exit();
        }

        // UPDATE: preserve the old photo unless a new one was uploaded.
        $stmt = $conn->prepare(
            "SELECT PHOTO FROM tbl_instructors WHERE ID = ?"
        );
        $stmt->bind_param("i", $id);
        $stmt->execute();
        $old = $stmt->get_result()->fetch_assoc();
        $stmt->close();

        if (!$old) {
            throw new InvalidArgumentException("Instructor not found.");
        }

        $oldPhoto = $old["PHOTO"] ?? null;
        $newPhoto = $uploadedPhoto ?? $oldPhoto;

        $stmt = $conn->prepare(
            "UPDATE tbl_instructors
             SET SALUTATION = ?, FIRSTNAME = ?, MIDDLENAME = ?,
                 LASTNAME = ?, PHOTO = ?
             WHERE ID = ?"
        );

        $stmt->bind_param(
            "sssssi",
            $salutation,
            $firstname,
            $middlename,
            $lastname,
            $newPhoto,
            $id
        );

        $stmt->execute();
        $stmt->close();

        if ($uploadedPhoto !== null) {
            delete_instructor_photo($oldPhoto, $uploadDir);
        }

        header("Location: instructors.php?updated=1");
        exit();
    } catch (InvalidArgumentException $e) {
        if ($uploadedPhoto !== null) {
            delete_instructor_photo($uploadedPhoto, $uploadDir);
        }

        $error = $e->getMessage();
    } catch (Throwable $e) {
        if ($uploadedPhoto !== null) {
            delete_instructor_photo($uploadedPhoto, $uploadDir);
        }

        error_log("Instructor operation failed: " . $e->getMessage());
        $error = "Unable to complete the operation. Please check your input and try again.";
    }
}

